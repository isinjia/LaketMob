# -*- coding: utf-8 -*-
"""스킨 진화 형태의 원작 스킨 이름 추출 → js/skinnames.js
CharSkin.xlsb (FullbodyIMG_<base>_NSk → 이름 ID) + Localization.xlsb (ID → 한국어)"""
import os, re, json
from pyxlsb import open_workbook
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
TB = 'E:/LAO/TAable_BattleRenewal'
src = open(os.path.join(HERE, 'extract_assets.py'), encoding='utf-8').read()
ns = {'__file__': os.path.join(HERE, 'extract_assets.py')}; exec(src.split('def ff(')[0], ns)
forms = json.loads(re.search(r'const FORMS = (\{.*?\});\n', open(os.path.join(ROOT, 'js', 'forms.js'), encoding='utf-8').read()).group(1))
want = {}
for key, e in forms.items():
    m = re.search(r'FullbodyIMG_(\w+?)_N\.png', ns['UNITS'][key][0]); base = m.group(1)
    for k, f in enumerate(e['forms'], 1): want['FullbodyIMG_%s_%s' % (base, f['skin'])] = '%s_%d' % (key, k)
ids = {}
with open_workbook(os.path.join(TB, 'CharSkin.xlsb')) as wb:
    with wb.get_sheet('Table_CharSkin') as sh:
        for r in sh.rows():
            v = [c.v for c in r]
            if len(v) > 8 and v[8] in want and v[4] is not None: ids[v[4] if isinstance(v[4], str) else str(int(v[4]))] = want[v[8]]
print('ids', len(ids), 'of', len(want))
names = {}
with open_workbook(os.path.join(TB, 'Localization.xlsb')) as wb:
    for s in wb.sheets:
        with wb.get_sheet(s) as sh:
            hdr = None
            for r in sh.rows():
                v = [c.v for c in r]
                if hdr is None and any(isinstance(x, str) and x.strip().lower() in ('ko', 'kor', 'korean', 'kr') for x in v): hdr = v
                for i, x in enumerate(v[:4]):
                    k = x if isinstance(x, str) else (str(int(x)) if isinstance(x, float) else None)
                    if k in ids and ids[k] not in names:
                        txt = next((y for y in v[i + 1:] if isinstance(y, str) and re.search('[가-힣]', y)), None)
                        if txt: names[ids[k]] = txt.strip()
print('names', len(names))
with open(os.path.join(ROOT, 'js', 'skinnames.js'), 'w', encoding='utf-8') as fp:
    fp.write('// auto-generated by tools/extract_skinnames.py : 스킨 진화 형태의 원작 스킨 이름\nconst SKIN_NAMES = ' + json.dumps(names, ensure_ascii=False, indent=0) + ';\n')

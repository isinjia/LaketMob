"""원작 표의 플레이어 캐릭터를 추가한다. 기존 번호/능력치는 보존한다.
python tools/expand_roster.py --assets E:/LAO_Google_QA/Assets --table ../7_LAO_3Kingdom/tools/lao_data.json
"""
import argparse, ast, json, re
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
a = argparse.ArgumentParser(); a.add_argument('--assets', type=Path, required=True); a.add_argument('--table', type=Path, required=True)
args = a.parse_args()
db = json.loads(args.table.read_text(encoding='utf-8'))
fb = args.assets / 'AssetBundleResourceSub/Texture/FullbodyImg'
ic = args.assets / 'AssetBundleResource/Texture/PCInvenIcon'
existing = set(re.findall(r"key: '([^']+)'", (ROOT/'js/data.js').read_text(encoding='utf-8')))
units = next(ast.literal_eval(n.value) for n in ast.parse((ROOT/'tools/extract_assets.py').read_text(encoding='utf-8')).body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='UNITS' for t in n.targets))
alias = {}
for k,(full,icon,voice) in units.items():
    if icon: alias[icon.removeprefix('InvenIcon_').removesuffix('_N.png')] = k
factions = {}
for t in db['troop']:
    for k in t['members']: factions.setdefault(k,t['name'])
roles = ['보호기','공격기','지원기']
rows=[]; skipped=[]; jobs=[]
for r in db['pc']:
    stem=r['key'].removeprefix('Char_').removesuffix('_N')
    if not stem.startswith(('3P_','AGS_','BR_','DS_','PECS_','ST_')) or 'Dummy' in stem or 'Lemonade' in stem: continue
    key=alias.get(stem,stem.split('_',1)[1].lower())
    if key in existing: continue
    full=[p for p in fb.glob('*'+stem+'_*') if p.suffix=='.png' and not any(t in p.name for t in ['_Dam','_BG','_Dialog','_ND'])]
    icons=list(ic.glob('InvenIcon_'+stem+'_*.png'))
    score=lambda p: (0 if p.stem.endswith('_N') else 1 if p.stem.endswith('_NS0') else 2, len(p.name),p.name)
    if not full or not icons: skipped.append(stem); continue
    full.sort(key=score);icons.sort(key=score)
    cls={0:'light',1:'heavy',2:'air'}.get(r['cls'],'light'); role=int(r['role']); rank={2:'B',3:'A',4:'S',5:'SS'}.get(r['grade'],'B')
    element=next((el for token,el in [('Ignis','fire'),('Salamander','fire'),('Sadius','fire'),('Cerberus','fire'),('Sona','elec'),('Alexandra','elec'),('Neodym','elec'),('Snow','ice'),('Glacies','ice'),('Lemon','elec')] if token in stem),None)
    types=[cls]+([element] if element else [])
    # 원작 스탯의 상대적 개성을 이 게임의 능력치 범위로 변환한다.
    hp=round(max(42,min(96,float(r['hp'])/4)));atk=round(max(38,min(100,float(r['atk'])*1.05)))
    defense=round(max(35,min(95,35+float(r['def'])*1.3)));spd=round(max(30,min(100,(float(r['spd'])-2.7)*30)))
    if role==0: hp=min(105,hp+10);defense=min(100,defense+8)
    faction=factions.get(r['key'],'오르카 합류 부대')
    basic={'light':'quick','heavy':'shell','air':'dive'}[cls]
    mid={'light':'blade','heavy':'barrage','air':'strafe'}[cls]
    last={'light':'rush','heavy':'railgun','air':'bomb'}[cls]
    moves=[[1,'shot'],[1,basic],[7,'guard' if role==0 else 'repair' if role==2 else 'taunt'],[14,mid],[24,last]]
    if element: moves += [[10,{'fire':'flamer','ice':'coldshot','elec':'shock'}[element]],[20,{'fire':'incend','ice':'cryo','elec':'plasma'}[element]]]
    moves.sort(key=lambda x:x[0])
    area={'B':'route1','A':'forest','S':'coast','SS':'snowfield'}[rank]
    if rank=='S':area=['coast','factory'][len(rows)%2]
    if rank=='SS':area=['snowfield','nest'][len(rows)%2]
    row=dict(key=key,name=r['name'],types=types,base=[hp,atk,defense,spd],rank=rank,catch={'B':180,'A':120,'S':65,'SS':30}[rank],exp={'B':60,'A':85,'S':120,'SS':175}[rank],kind='ags' if r['body']==1 else 'bio',faction=faction,moves=moves,desc=f"{faction} 소속 {roles[role]}인 {'AGS' if r['body']==1 else '바이오로이드'}. "+('합류 대사: '+r['join'].strip() if r.get('join') else '링크 코어로 영입할 수 있다.'),expanded=True,habitat=area,sourceId=r['key'])
    # 기존 NPC의 음성은 재사용. 이번에 추가하는 이미지에는 음성 파일이 없는 경우 표시한다.
    row['noVoice']=not (ROOT/'assets/voice'/f'{key}_start.mp3').exists()
    rows.append(row);jobs.append((key,full[0],icons[0]));existing.add(key)

def convert(job):
    key,full,icon=job
    for cat,src,size in [('full',full,720),('icon',icon,112)]:
        dest=ROOT/'assets'/cat/(key+'.webp')
        if dest.exists():continue
        with Image.open(src) as im:
            im=im.convert('RGBA');bb=im.getchannel('A').point(lambda a:255 if a>8 else 0).getbbox()
            if bb and cat=='full':im=im.crop(bb)
            im.thumbnail((size,size),Image.Resampling.LANCZOS);im.save(dest,'WEBP',quality=84,method=4)
with ThreadPoolExecutor(max_workers=4) as pool:list(pool.map(convert,jobs))
(ROOT/'js/rosterdata.js').write_text('// Generated by tools/expand_roster.py. Original table names; RPG moves/stats adapted.\nconst EXPANDED_ROSTER = '+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'added':len(rows),'skipped':skipped,'regions':{a:sum(x['habitat']==a for x in rows) for a in ['route1','forest','coast','factory','snowfield','nest']}},ensure_ascii=False))

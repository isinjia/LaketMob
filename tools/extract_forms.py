# -*- coding: utf-8 -*-
"""스킨 진화 형태 / 중파 일러스트 추출.
- 포획 가능한 유닛마다 스킨(NS1, NS2, ...)을 번호 순서대로 '진화 형태'로 쓴다.
- 스킨 일러스트: NSk.png 가 있으면 그대로, 없으면 2048x2048 부품(partN)만 합성. 일반 이미지가 없는 스킨은 제외.
- 중파: N_Dam / NSk_Dam (없으면 같은 규칙으로 Dam 부품 합성)
출력: assets/full/<key>_<k>.webp, assets/full/<key>[_<k>]_dam.webp, assets/icon/<key>_<k>.webp,
      assets/voice/<key>_<k>_<tag>.mp3, js/forms.js
"""
import os, re, json, subprocess
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
src = open(os.path.join(HERE, 'extract_assets.py'), encoding='utf-8').read()
ns = {'__file__': os.path.join(HERE, 'extract_assets.py')}
exec(src.split('def ff(')[0], ns)
UNITS, FB, IC, VO = ns['UNITS'], ns['FB'], ns['IC'], ns['VO']
VOICE_TAGS = ns['VOICE_TAGS']
OUT = os.path.join(ROOT, 'assets')
data = open(os.path.join(ROOT, 'js', 'data.js'), encoding='utf-8').read()
CATCH = [k for k, c in re.findall(r"\{ key: '([a-z]+)', name: '[^']+', types: \[[^\]]*\], base: \[[^\]]*\], rank: '[A-Z]+', catch: (\d+)", data) if int(c) > 0]
FILES = [f for f in os.listdir(FB) if f.lower().endswith('.png')]
IGNORE = re.compile(r'(bg|fx|parts?\d*_?bg)', re.I)


def trim(im):
    bb = im.split()[-1].point(lambda v: 255 if v > 8 else 0).getbbox()
    return im.crop(bb) if bb else im


def compose(base, skin, dam):
    """skin: 'N' or 'NS1'. returns Image or None"""
    pre = f'FullbodyIMG_{base}_{skin}'
    cands = [f for f in FILES if f.startswith(pre) and (len(f) == len(pre) + 4 or f[len(pre)] == '_')]
    def is_dam(f): return re.search(r'_dam', f[len(pre):], re.I) is not None
    cands = [f for f in cands if is_dam(f) == dam and not IGNORE.search(f[len(pre):].replace('.png', ''))]
    if not cands:
        return None
    single = [f for f in cands if re.fullmatch(r'(_dam)?\.png', f[len(pre):], re.I)]
    if single:
        return Image.open(os.path.join(FB, single[0])).convert('RGBA')
    parts = sorted(f for f in cands if re.search(r'part', f, re.I))
    ims = [Image.open(os.path.join(FB, f)).convert('RGBA') for f in parts]
    ims = [im for im in ims if im.size == (2048, 2048)]
    if not ims:
        return None
    out = Image.new('RGBA', (2048, 2048))
    for im in ims:
        out.alpha_composite(im)
    return out


def save_full(im, name):
    dst = os.path.join(OUT, 'full', name + '.webp')
    if os.path.exists(dst):
        return Image.open(dst).size
    im = trim(im)
    im.thumbnail((720, 720), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=86, method=4)
    return im.size


def ff(src, dst):
    if os.path.exists(dst):
        return
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', src, '-ac', '1', '-b:a', '64k', dst])


def find_voice(folder, tags):
    d = os.path.join(VO, folder)
    if not os.path.isdir(d):
        return None
    fs = sorted(f for f in os.listdir(d) if f.endswith('.mp3'))
    for t in tags:
        for f in fs:
            if t in f:
                return os.path.join(d, f)
    return None


forms, sizes = {}, {}
for key in CATCH:
    fb, ic, vo = UNITS[key]
    m = re.search(r'FullbodyIMG_(\w+?)_N\.png', fb)
    if not m:
        continue
    base = m.group(1)
    entry = {'dam': False, 'forms': []}
    d0 = compose(base, 'N', True)
    if d0 is not None:
        sizes[key + '_dam'] = save_full(d0, key + '_dam'); entry['dam'] = True
    skins = sorted({re.match(r'FullbodyIMG_%s_(NS\d+)' % re.escape(base), f).group(1) for f in FILES if re.match(r'FullbodyIMG_%s_NS\d+' % re.escape(base), f)}, key=lambda s: int(s[2:]))
    k = 0
    for skin in skins:
        im = compose(base, skin, False)
        if im is None:
            continue
        k += 1
        name = f'{key}_{k}'
        sizes[name] = save_full(im, name)
        f = {'skin': skin, 'dam': False, 'voice': False}
        dm = compose(base, skin, True)
        if dm is not None:
            sizes[name + '_dam'] = save_full(dm, name + '_dam'); f['dam'] = True
        icp = os.path.join(IC, f'InvenIcon_{base}_{skin}.png')
        idst = os.path.join(OUT, 'icon', name + '.webp')
        if os.path.exists(icp) and not os.path.exists(idst):
            Image.open(icp).convert('RGBA').save(idst, 'WEBP', quality=90)
        f['icon'] = os.path.exists(idst)
        if vo:
            for tag, cands in VOICE_TAGS.items():
                s = find_voice(vo + skin, cands)
                if s:
                    ff(s, os.path.join(OUT, 'voice', f'{name}_{tag}.mp3')); f['voice'] = True
        entry['forms'].append(f)
    forms[key] = entry
    print(key, 'dam' if entry['dam'] else '-', [x['skin'] + ('*' if x['dam'] else '') for x in entry['forms']])

with open(os.path.join(ROOT, 'js', 'forms.js'), 'w', encoding='utf-8') as fp:
    fp.write('// auto-generated by tools/extract_forms.py : 스킨 진화 형태 / 중파 일러스트\n')
    fp.write('const FORMS = ' + json.dumps(forms, ensure_ascii=False) + ';\n')
    fp.write('const FORM_SIZES = ' + json.dumps(sizes) + ';\n')
print('done', len(forms))

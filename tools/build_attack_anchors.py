"""Compile image-local effect landmarks; alpha-snap to prevent floating muzzle flashes.
The source JSON is hand-reviewed against contact sheets of every full-body asset.
The output is static: there is no extra full-size pixel read or texture on phones.
"""
import json, math
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
profiles=json.loads((ROOT/'tools/attack-anchor-profiles.json').read_text(encoding='utf-8'))
result={}; corrections=[]
for key,p in profiles.items():
    with Image.open(ROOT/'assets/full'/f'{key}.webp') as im:
        a=im.convert('RGBA').getchannel('A'); a.thumbnail((180,180));w,h=a.size
        pixels=a.load(); px=p['emit'][0]*(w-1);py=p['emit'][1]*(h-1)
        candidates=[(x,y) for y in range(h) for x in range(w) if pixels[x,y]>100]
        x,y=min(candidates,key=lambda t:((t[0]-px)/w)**2+((t[1]-py)/h)**2)
        dist=math.hypot((x-px)/w,(y-py)/h)
        if dist>.08:corrections.append([key,round(dist,3)])
        emit=[round(x/max(1,w-1),4),round(y/max(1,h-1),4)]
        # Opaque upper-body centroid. Wide weapons do not shift the impact to their tips.
        central=[(x,y) for x,y in candidates if .20*w<x<.80*w and .25*h<y<.60*h]
        if not central:central=candidates
        hx=sum(t[0] for t in central)/len(central);hy=sum(t[1] for t in central)/len(central)
        hx,hy=min(central,key=lambda t:((t[0]-hx)/w)**2+((t[1]-hy)/h)**2)
        hit=[round(hx/max(1,w-1),4),round(hy/max(1,h-1),4)]
        result[key]={'kind':p['kind'],'emit':emit,'hit':hit}
path=ROOT/'js/battleanchor-data.js'
path.write_text('// Generated by tools/build_attack_anchors.py from reviewed image landmarks.\nconst BATTLE_ANCHORS = '+json.dumps(result,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'images':len(result),'largerCorrections':corrections},ensure_ascii=False))
